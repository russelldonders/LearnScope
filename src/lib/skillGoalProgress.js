// Pure goal logic: how a goal's values are read back out of the activity log
// and turned into progress. Nothing here is stored -- progress is always
// worked out from the statements, so it can't go stale when an entry is
// backdated, corrected or deleted.

export const MEASURE_KINDS = ['count', 'number', 'duration', 'pace', 'activities', 'practice_time']
export const DERIVED_KINDS = ['activities', 'practice_time']
export const ACTIVITY_COUNT_METRIC = 'activity_count'
export const PRACTICE_MINUTES_METRIC = 'practice_minutes'

export function isDerivedKind(kind) {
  return DERIVED_KINDS.includes(kind)
}

export function localDateString(date = new Date()) {
  const year = date.getFullYear()
  const month = String(date.getMonth() + 1).padStart(2, '0')
  const day = String(date.getDate()).padStart(2, '0')
  return `${year}-${month}-${day}`
}

// A date picked in a form means that day where the learner is. Midday local
// time keeps it on that calendar day whichever timezone later reads it.
export function dateToTimestamp(dateString) {
  return new Date(`${dateString}T12:00:00`).toISOString()
}

function startOfPeriod(date, period) {
  const d = new Date(date.getFullYear(), date.getMonth(), date.getDate())
  if (period === 'week') d.setDate(d.getDate() - ((d.getDay() + 6) % 7)) // Monday
  if (period === 'month') d.setDate(1)
  if (period === 'year') d.setMonth(0, 1)
  return d
}

// One value per relevant statement, oldest first. activities/practice_time
// read every activity the learner logged on the skill, excluding the ones
// generated by diagnostics or by someone else rating them.
// A count and a number in the same unit are the same quantity -- whole or
// not -- so a goal corrected from one to the other (102 kg first saved as a
// count) keeps its earlier entries.
const PLAIN_NUMBER_KINDS = new Set(['count', 'number'])
function sameMeasureKind(a, b) {
  return a === b || (PLAIN_NUMBER_KINDS.has(a) && PLAIN_NUMBER_KINDS.has(b))
}

export function goalReadings(goal, statements) {
  const readings = []
  for (const row of statements ?? []) {
    let value = null
    if (goal.measure_kind === 'activities' || goal.measure_kind === 'practice_time') {
      if (isDiagnosticStatement(row.statement) || isPeerRatingStatement(row.statement)) continue
      value = goal.measure_kind === 'activities' ? 1 : durationMinutes(row.statement)
      if (value === 0) continue
    } else {
      // The name alone isn't enough: entries outlive a deleted goal, and a later
      // goal reusing the name in other units mustn't pick up old numbers.
      const measurement = measurementsFromStatement(row.statement).find(
        (m) => m.metric === goal.metric && m.unit === goal.unit && sameMeasureKind(m.kind, goal.measure_kind),
      )
      if (!measurement) continue
      value = Number(measurement.value)
      if (!Number.isFinite(value)) continue
    }
    readings.push({ id: row.id, date: new Date(row.recorded_at), value, row })
  }
  return readings.sort((a, b) => a.date - b.date)
}

// The latest entry that holds a value for this goal, for "same as last time".
// Null when there isn't one, or when the goal only counts activities.
export function lastGoalEntry(goal, statements) {
  if (isDerivedKind(goal.measure_kind)) return null
  const readings = goalReadings(goal, statements)
  return readings.length ? readings[readings.length - 1].row : null
}

function startOfDayFromString(dateString) {
  return new Date(`${dateString}T00:00:00`)
}

function isBetter(goal, a, b) {
  return goal.direction === 'lower' ? a < b : a > b
}

export function isTargetReached(goal, current) {
  if (goal.target_value == null || current == null) return false
  const target = Number(goal.target_value)
  return goal.direction === 'lower' ? current <= target : current >= target
}

// current is the number the goal is judged on: the best value since the goal
// began, or the running total for the current period (or since it began, when
// it has no period). Values from before the goal began stay on the chart but
// don't count towards it -- 40 push-ups in 2019 shouldn't complete a goal set
// today -- and the latest of them is used as the starting point.
export function computeGoalProgress(goal, statements, now = new Date()) {
  const readings = goalReadings(goal, statements)
  const startedAt = startOfDayFromString(goal.started_on)
  const sinceStart = readings.filter((r) => r.date >= startedAt)
  const earlier = readings.filter((r) => r.date < startedAt)
  const lastLogged = readings.length > 0 ? readings[readings.length - 1].date : null

  let current = null
  let baseline = null
  if (goal.aggregation === 'total') {
    const periodStart = goal.period ? startOfPeriod(now, goal.period) : startedAt
    const from = periodStart > startedAt ? periodStart : startedAt
    const counted = readings.filter((r) => r.date >= from)
    current = counted.reduce((sum, r) => sum + r.value, 0)
    baseline = 0
  } else {
    for (const reading of sinceStart) {
      if (current === null || isBetter(goal, reading.value, current)) current = reading.value
    }
    baseline = earlier.length > 0 ? earlier[earlier.length - 1].value : sinceStart[0]?.value ?? null
  }

  const target = goal.target_value == null ? null : Number(goal.target_value)
  const reached = isTargetReached(goal, current)
  // A starting point already past the target (99 push-ups in the past, aiming
  // for 40 now) says nothing about progress towards it, so measure from the
  // first value since the goal began instead.
  const baselineStillAhead = baseline !== null && target !== null && isTargetReached(goal, baseline)
  const start = baselineStillAhead ? sinceStart[0]?.value ?? null : baseline
  let percent = null
  if (target !== null && current !== null && start !== null) {
    if (reached) percent = 100
    else if (start === target) percent = 0
    else percent = Math.max(0, Math.min(100, ((current - start) / (target - start)) * 100))
  }

  return { readings, current, baseline, target, reached, percent, lastLogged, entryCount: readings.length }
}

// Points for the chart. Best-value goals plot each entry; period totals plot
// one point per period; a total with no period plots the running total.
export function goalChartPoints(goal, statements) {
  const readings = goalReadings(goal, statements)
  if (goal.aggregation !== 'total') return readings.map((r) => ({ date: r.date, value: r.value }))
  if (!goal.period) {
    const startedAt = startOfDayFromString(goal.started_on)
    let total = 0
    return readings
      .filter((r) => r.date >= startedAt)
      .map((r) => {
        total += r.value
        return { date: r.date, value: total }
      })
  }
  const byPeriod = new Map()
  for (const reading of readings) {
    const start = startOfPeriod(reading.date, goal.period).getTime()
    byPeriod.set(start, (byPeriod.get(start) ?? 0) + reading.value)
  }
  return [...byPeriod.entries()]
    .sort(([a], [b]) => a - b)
    .map(([start, value]) => ({ date: new Date(start), value }))
}

function nextPeriodStart(date, period) {
  const next = new Date(date)
  if (period === 'day') next.setDate(next.getDate() + 1)
  if (period === 'week') next.setDate(next.getDate() + 7)
  if (period === 'month') next.setMonth(next.getMonth() + 1)
  if (period === 'year') next.setFullYear(next.getFullYear() + 1)
  return next
}

export const PERIOD_BAR_LIMITS = { day: 14, week: 12, month: 12, year: 6 }

// One bar per day, week, month or year of a repeating total, from the period
// the goal began in up to the current one, including periods with nothing
// logged. Each says whether it met the target: "met", "missed", "inProgress"
// for the current period while it can still be met, or "none" with no target.
// Only the most recent periods are returned.
export function goalPeriodBars(goal, statements, now = new Date()) {
  if (goal.aggregation !== 'total' || !goal.period) return []
  return allPeriodBars(goal, statements, now).slice(-PERIOD_BAR_LIMITS[goal.period])
}

// How many periods in a row met the target, ending with the current period
// when it's already met, or with the one before while the current period can
// still be met. Zero for goals that don't repeat or have no target.
export function goalStreak(goal, statements, now = new Date()) {
  if (goal.aggregation !== 'total' || !goal.period || goal.target_value == null) return 0
  const bars = allPeriodBars(goal, statements, now)
  if (bars.at(-1)?.status === 'inProgress') bars.pop()
  let streak = 0
  while (bars.length > 0 && bars.pop().status === 'met') streak += 1
  return streak
}

export const MINI_HISTORY_LENGTH = 7

// A total with a target that doesn't repeat in practice: no period, or a
// deadline that falls before the next period starts.
export function isBuildUpGoal(goal, now = new Date()) {
  if (goal.aggregation !== 'total' || goal.target_value == null) return false
  if (!goal.period) return true
  if (!goal.target_date) return false
  return goal.target_date < localDateString(nextPeriodStart(startOfPeriod(now, goal.period), goal.period))
}

// The small chart on a dashboard goal tile. A repeating total shows its last
// few days, weeks, months or years, each marked met or missed; any other goal
// shows its last few entries, the latest marked as current. Entries aren't
// judged against the target one by one: a single plank time short of a
// stretch target isn't a miss the way a missed week is.
//
// A total building up to one target -- no period, or a deadline before the
// current period ends ("10 mandarins by the end of the year") -- has no run
// of periods worth charting, so it gets { kind: 'progress' } and the tile
// shows how far along it is instead.
export function goalMiniHistory(goal, statements, now = new Date()) {
  const target = goal.target_value == null ? null : Number(goal.target_value)
  if (isBuildUpGoal(goal, now)) return { kind: 'progress' }
  if (goal.aggregation === 'total' && goal.period) {
    return { kind: 'periods', target, bars: allPeriodBars(goal, statements, now).slice(-MINI_HISTORY_LENGTH) }
  }
  const readings = goalReadings(goal, statements).slice(-MINI_HISTORY_LENGTH)
  return {
    kind: 'entries',
    target: goal.aggregation === 'total' ? null : target,
    bars: readings.map((reading, index) => ({
      start: reading.date,
      value: reading.value,
      status: 'none',
      current: index === readings.length - 1,
    })),
  }
}

// The goals this one replaced when its target or date changed, oldest first,
// as { target_value, closed_on }, so past periods can be judged by the target
// that applied then. allGoals holds the skill's goals, replaced ones included.
export function withTargetHistory(goal, allGoals) {
  const byId = new Map((allGoals ?? []).map((other) => [other.id, other]))
  const history = []
  const seen = new Set([goal.id])
  let previous = byId.get(goal.replaces_goal_id)
  while (previous && !seen.has(previous.id)) {
    seen.add(previous.id)
    history.unshift({ target_value: previous.target_value, closed_on: previous.closed_on })
    previous = byId.get(previous.replaces_goal_id)
  }
  return { ...goal, target_history: history }
}

// The target in force on a day: that of the earliest replaced goal still open
// on it, else the goal's own. A goal replaced on a day no longer applies that
// day, so a period ending on the day a target changed uses the new one.
function targetOn(goal, dateString) {
  const earlier = (goal.target_history ?? []).find((entry) => entry.closed_on && entry.closed_on > dateString)
  const value = earlier ? earlier.target_value : goal.target_value
  return value == null ? null : Number(value)
}

function allPeriodBars(goal, statements, now) {
  const startedAt = startOfDayFromString(goal.started_on)
  const readings = goalReadings(goal, statements).filter((r) => r.date >= startedAt)
  const current = startOfPeriod(now, goal.period).getTime()
  const bars = []
  for (let start = startOfPeriod(startedAt, goal.period); start.getTime() <= current; start = nextPeriodStart(start, goal.period)) {
    const end = nextPeriodStart(start, goal.period)
    // Each entry that went into the period, oldest first, so a chart can show
    // a total of 60 as three logs of 20.
    const parts = readings.filter((r) => r.date >= start && r.date < end).map((r) => r.value)
    const value = parts.reduce((sum, part) => sum + part, 0)
    const isCurrent = start.getTime() === current
    const lastDay = new Date(end)
    lastDay.setDate(lastDay.getDate() - 1)
    const target = isCurrent ? (goal.target_value == null ? null : Number(goal.target_value)) : targetOn(goal, localDateString(lastDay))
    let status = 'none'
    if (target !== null) status = value >= target ? 'met' : isCurrent ? 'inProgress' : 'missed'
    // A met period that went past the target, so a chart can tell it apart
    // from one that only just made it. It still counts as met everywhere.
    const exceeded = target !== null && value > target
    bars.push({ start: new Date(start), value, parts, status, exceeded, current: isCurrent, target })
  }
  return bars
}

function addDays(dateString, days) {
  const date = startOfDayFromString(dateString)
  date.setDate(date.getDate() + days)
  return localDateString(date)
}

// The day a goal's logging rhythm next asks for an entry, counted from the last
// entry, or from the day the goal began when nothing has been logged since.
// Null when the goal has no rhythm.
export function nextLogDate(goal, lastLogged) {
  if (!goal.log_every_days) return null
  const lastDay = lastLogged ? localDateString(lastLogged) : null
  const from = lastDay && lastDay > goal.started_on ? lastDay : goal.started_on
  return addDays(from, goal.log_every_days)
}

// What to say after a new entry: a new best or a target just reached are worth
// celebrating. Returns a translation key, or null for an ordinary entry.
export function goalLogFeedback(goal, before, after) {
  if (!before.reached && after.reached) return 'skillGoals.dashboard.reachedNow'
  if (
    goal.aggregation === 'best' &&
    before.current != null &&
    after.current != null &&
    isBetter(goal, after.current, before.current)
  ) {
    return 'skillGoals.dashboard.newBest'
  }
  return null
}

// Goals in the order they need the learner: those due a log first (most
// overdue first), then the nearest target dates, then the newest.
export function sortGoalsForAttention(items, today = localDateString()) {
  const dueDate = (item) => (item.nextLog && item.nextLog <= today ? item.nextLog : null)
  return [...items].sort((a, b) => {
    const dueA = dueDate(a)
    const dueB = dueDate(b)
    if (dueA !== dueB) {
      if (!dueA) return 1
      if (!dueB) return -1
      return dueA.localeCompare(dueB)
    }
    const targetA = a.goal.target_date
    const targetB = b.goal.target_date
    if (targetA !== targetB) {
      if (!targetA) return 1
      if (!targetB) return -1
      return targetA.localeCompare(targetB)
    }
    return String(b.goal.created_at).localeCompare(String(a.goal.created_at))
  })
}

// Accepts "25:30" or "1:05:00". Returns seconds, or null if it can't be read as
// a time. A bare number is refused because it's ambiguous: "45" could be
// seconds on a plank or minutes on a run.
export function parseClock(text) {
  const value = String(text ?? '').trim()
  if (!/^\d+(:\d{1,2}){1,2}$/.test(value)) return null
  const parts = value.split(':').map(Number)
  if (parts.slice(1).some((part) => part >= 60)) return null
  return parts.reduce((total, part) => total * 60 + part, 0)
}

// Whole seconds per distance unit, never rounded to a misleading precision.
export function computePaceSeconds(distance, durationSeconds) {
  const d = Number(distance)
  const s = Number(durationSeconds)
  if (!(d > 0) || !(s > 0)) return null
  return Math.round(s / d)
}

export function distanceUnitFromPace(unit) {
  return unit === 'min/mi' ? 'mi' : 'km'
}

export function formatNumber(value) {
  const number = Number(value)
  if (!Number.isFinite(number)) return ''
  return String(Math.round(number * 100) / 100)
}

// A value in the goal's own terms, e.g. "32 push-ups", "5:00 min/km", "25:30".
export function formatGoalValue(goal, value) {
  if (value == null) return ''
  if (goal.measure_kind === 'duration') return formatClock(value)
  if (goal.measure_kind === 'pace') return `${formatClock(value)} ${goal.unit}`
  return `${formatNumber(value)} ${goal.unit}`
}

// Plain lowercase metric name used to match values back to a goal. Falls back
// to a generated name when the title has no Latin letters to build one from.
export function slugifyMetric(text) {
  const slug = String(text ?? '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 50)
  return slug || `measure_${Math.random().toString(36).slice(2, 10)}`
}

// Two goals may share a metric only if its values mean the same thing. A
// different kind or unit gets its own series rather than mixing numbers on one
// chart. So does a different way of counting: "best set" and "today's total"
// answer different questions, so an entry for one mustn't count for the other.
export function resolveMetric(metric, kind, unit, aggregation, existingGoals) {
  const conflicts = (name) =>
    (existingGoals ?? []).some(
      (g) => g.metric === name && (g.measure_kind !== kind || g.unit !== unit || g.aggregation !== aggregation),
    )
  if (!conflicts(metric)) return metric
  let suffix = 2
  while (conflicts(`${metric}_${suffix}`)) suffix += 1
  return `${metric}_${suffix}`
}

// The numbers a tracker entry writes to the activity. Pace keeps the distance
// and time it was worked out from, so a correction can start from what the
// learner actually typed.
export function buildGoalMeasurement(goal, input) {
  const base = { metric: goal.metric, kind: goal.measure_kind, unit: goal.unit }
  switch (goal.measure_kind) {
    case 'count':
    case 'number':
      return { ...base, value: Number(input.value) }
    case 'duration':
      return { ...base, value: input.durationSeconds }
    case 'pace':
      return {
        ...base,
        value: computePaceSeconds(input.distance, input.durationSeconds),
        inputs: { distance: Number(input.distance), durationSeconds: input.durationSeconds },
      }
    case 'activities':
      return { ...base, metric: ACTIVITY_COUNT_METRIC, value: 1 }
    case 'practice_time':
      return { ...base, metric: PRACTICE_MINUTES_METRIC, value: Math.round(input.durationSeconds / 60) }
    default:
      throw new Error(`Unknown goal measure: ${goal.measure_kind}`)
  }
}

// Whole minutes for the activity's standard xAPI duration, when the entry has
// a time at all.
export function entryDurationMinutes(goal, input) {
  if (!['duration', 'pace', 'practice_time'].includes(goal.measure_kind)) return 0
  return Math.round((input.durationSeconds ?? 0) / 60)
}

// A statement with one tracker entry corrected. Only the values, date, note and
// (for an "activities" goal) name change; its id, skills, experience and any
// other measurements stay as they were.
export function applyEntryCorrection(statement, goal, { input, timestamp, note, activityTitle }) {
  const measurement = buildGoalMeasurement(goal, input)
  const minutes = entryDurationMinutes(goal, input)
  const extensions = statement.result?.extensions ?? {}
  const existing = measurementsFromStatement(statement)
  const others = existing.filter((m) => m.metric !== measurement.metric)
  const previous = existing.find((m) => m.metric === measurement.metric)
  // What it said before stays on the record, so a correction can't quietly
  // rewrite history.
  const corrections = [
    ...(previous?.corrections ?? []),
    { value: previous?.value ?? null, timestamp: statement.timestamp, corrected_at: new Date().toISOString() },
  ]
  const result = {
    ...statement.result,
    extensions: { ...extensions, [MEASUREMENT_EXTENSION_IRI]: [...others, { ...measurement, corrections }] },
  }
  if (['duration', 'pace', 'practice_time'].includes(goal.measure_kind)) {
    const duration = buildDuration(Math.floor(minutes / 60), minutes % 60)
    if (duration) result.duration = duration
    else delete result.duration
  }

  const definition = { ...statement.object?.definition }
  if (note) definition.description = { 'en-US': note }
  else delete definition.description
  if (activityTitle) definition.name = { 'en-US': activityTitle }

  return {
    ...statement,
    timestamp,
    result,
    object: { ...statement.object, definition },
  }
}

// Validates what the learner typed against the goal's measure. Returns a
// translation key for the problem, or null when it's fine.
export function validateEntryInput(goal, input) {
  switch (goal.measure_kind) {
    case 'count': {
      const value = Number(input.value)
      return input.value !== '' && Number.isInteger(value) && value >= 0 ? null : 'skillGoals.errorWholeNumber'
    }
    case 'number': {
      const value = Number(input.value)
      return input.value !== '' && Number.isFinite(value) && value >= 0 ? null : 'skillGoals.errorNumber'
    }
    case 'duration':
    case 'practice_time':
      return input.durationSeconds > 0 ? null : 'skillGoals.errorTime'
    case 'pace':
      if (!(Number(input.distance) > 0)) return 'skillGoals.errorDistance'
      return input.durationSeconds > 0 ? null : 'skillGoals.errorTime'
    default:
      return null
  }
}
